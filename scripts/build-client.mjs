#!/usr/bin/env node
/**
 * Build the DSH client module from src/client into a single client.js.
 *
 * DSH's client loader evaluates `window.__ModuleLoader__.load({ factory })`
 * with its own `require`, so the bundle is wrapped in that envelope. The
 * factory body sets `globalThis.__qpReact` before the bundle runs; runtime.js
 * reads it at module-evaluation time.
 *
 * esbuild is invoked as its platform binary (stdio inherited) so the build also
 * works under the DSH Windows sandbox, where piped child stdout is denied. The
 * npm `bin/esbuild` shim is a JS file on Windows but the native ELF on Linux,
 * so it is only used as a fallback.
 */
import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const pkg = JSON.parse(readFileSync('package.json', 'utf8'))
const temp = join(root, '.tmp-client-bundle.js')

function esbuildCommand() {
  const platformPackage = `@esbuild/${process.platform}-${process.arch}`
  const nativeBinary = join(
    root,
    'node_modules',
    platformPackage,
    process.platform === 'win32' ? 'esbuild.exe' : join('bin', 'esbuild'),
  )
  if (existsSync(nativeBinary)) return { command: nativeBinary, prefix: [] }

  const shim = join(root, 'node_modules', 'esbuild', 'bin', 'esbuild')
  if (existsSync(shim)) {
    const magic = readFileSync(shim).subarray(0, 4).toString('latin1')
    if (magic.startsWith('\x7fELF') || magic.startsWith('MZ')) return { command: shim, prefix: [] }
    return { command: process.execPath, prefix: [shim] }
  }

  throw new Error('esbuild is not installed; run npm install')
}

const { command, prefix } = esbuildCommand()
const result = spawnSync(
  command,
  [
    ...prefix,
    'src/client/main.js',
    '--bundle',
    '--format=iife',
    '--global-name=__qpModule',
    '--platform=browser',
    '--target=es2020',
    '--charset=utf8',
    '--legal-comments=none',
    `--outfile=${temp}`,
  ],
  { cwd: root, stdio: 'inherit' },
)
if (result.error) throw result.error
if (result.status !== 0) {
  rmSync(temp, { force: true })
  throw new Error(`esbuild exited ${String(result.status)}`)
}

const body = readFileSync(temp, 'utf8').replace(/\s+$/u, '')
rmSync(temp, { force: true })

const indented = body
  .split('\n')
  .map((line) => (line ? `      ${line}` : line))
  .join('\n')

// The module id must follow the package name: the loader rejects a factory id
// that a leftover copy of another package already registered.
const moduleId = pkg.name

const output = `/* Generated by scripts/build-client.mjs — edit src/client/ instead. */
window.__ModuleLoader__.load({
  id: '${moduleId}',
  factory(require) {
    globalThis.__qpReact = require('react')
    try {
${indented}
      return __qpModule.default
    } finally {
      delete globalThis.__qpReact
    }
  },
})
`

const previous = (() => {
  try {
    return readFileSync('client.js', 'utf8')
  } catch {
    return ''
  }
})()
writeFileSync('client.js', output)
console.log(`client.js ${output.length} bytes${output === previous ? ' (unchanged)' : ''}`)
